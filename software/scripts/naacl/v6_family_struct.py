#!/usr/bin/env python3
"""Map-Reflect minus the schema-size baseline per family, each at its own frozen operating point.

Every number is read from the macros in paper/numbers_v6.tex (facts F-RevTwoRobVsStruct* from
docs/naacl/results/rev2_robustness_facts.json and F-VFiveMainVsStruct from docs/naacl/results/v5_facts.json);
nothing is typed in here.

Writes only paper/tab6_family_struct.tex.

Usage: .venv/bin/python scripts/naacl/v6_family_struct.py   (after v6_numbers.py)
"""
import sys

from v6_compact import ROOT, has, no_dash, num, signed

FAMILIES = [("ITOpsGraph", "RevTwoRobVsStructFamITOps"), ("NL2GQL", "RevTwoRobVsStructFamNLGQL"),
            ("ToolBench", "RevTwoRobVsStructFamToolBench"), ("OMOP", "RevTwoRobVsStructFamOMOP"),
            ("Valentine", "RevTwoRobVsStructFamValentine")]
SUMMARIES = [("Pooled", "VFiveMainVsStruct"), ("Family mean", "RevTwoRobVsStructMacroFamilies"),
             ("Dataset mean", "RevTwoRobVsStructMacroDatasets")]


def cell(key):
    return f"{signed(num(key))} [{signed(num(key + 'Lo'))}, {signed(num(key + 'Hi'))}]"


def table():
    for _, key in FAMILIES + SUMMARIES:
        for k in (key, key + "Lo", key + "Hi"):
            if not has(k):
                sys.exit(f"numbers_v6.tex has no \\F{k}")
    t = ["% Generated by scripts/naacl/v6_family_struct.py from paper/numbers_v6.tex; do not edit by hand.",
         r"\begin{table}[t]", r"\centering\small\setlength{\tabcolsep}{4pt}", r"\begin{tabular}{lr}", r"\toprule",
         r"Family or summary & Difference [95\% CI] \\", r"\midrule"]
    t += [f"{name} & {cell(key)} \\\\" for name, key in FAMILIES]
    t.append(r"\midrule")
    t += [f"{name} & {cell(key)} \\\\" for name, key in SUMMARIES]
    t += [r"\bottomrule", r"\end{tabular}", r"\gencaption", r"\label{tab:family_struct}", r"\end{table}"]
    return "\n".join(t) + "\n"


def main():
    t = table()
    no_dash(t)
    (ROOT / "paper/tab6_family_struct.tex").write_text(t)
    print("wrote paper/tab6_family_struct.tex")


if __name__ == "__main__":
    main()
