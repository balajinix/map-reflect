#!/usr/bin/env python3
"""R11 (docs/naacl/v6/PLAN_PHASE2.md): the compact main-text versions of the routers and interventions tables.

Every number is read from the macros in paper/numbers_v6.tex (each one a fact in docs/naacl/v6/FACTS.md, written by
scripts/naacl/v6_numbers.py); nothing is typed in here. The only arithmetic is the accuracy of the two routers that
have no accuracy fact of their own (the error trigger and struct-or-margin), which is the first-pass accuracy plus
their change, as in the full table. Cells keep the precision of the facts (two decimals): rounding a two-decimal fact again to one decimal can
disagree with the full table, which rounds the unrounded value (87.95 is 87.9 there). The full tables
(paper/tab6_main.tex, paper/tab6_interventions.tex) stay as the appendix versions; a cross-check at the end confirms
that every compact number agrees with the same cell there to that cell's own precision.

Writes paper/tab6_main_compact.tex and paper/tab6_interventions_compact.tex.

Usage: .venv/bin/python scripts/naacl/v6_compact.py   (after v6_numbers.py)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MACROS = ROOT / "paper/numbers_v6.tex"

# Router rows of the compact Table 1: label, fact tag (F<tag>Acc, F<tag>Gain, F<tag>Calls), bold.
ROUTERS = [("No reflection", "Keep"), ("Declined only", "Decl"), ("Random selection", "Rand"),
           ("Random selection, per dataset", "RandDS"), ("Random selection, per stratum", "RandStrat"),
           ("Schema-size baseline", "Struct"), ("Error trigger", "RouterErr"),
           ("Map-Reflect", "Main"), ("Schema size or margin", "Union"), ("Reflect on all", "Every"), ("Oracle", "Oracle")]
# Method v5 (when F-VFive* facts exist): the router table's v5 rows, all on the same v5 second pass.
# Rules on the shared second pass by increasing change, then the reference rows under an italic header.
ROUTERS_V5 = [("No reflection", "VFiveKeep"), ("Random selection", "VFiveRandom"), ("Schema-size baseline", "VFiveStruct"),
              ("Margin, fixed thresholds", "VFiveMarginOld"), ("Map-Reflect", "VFiveMain"),
              ("Benefit or schema size", "VFiveUnion"), (r"Margin, $t_m$ refit", "VFiveMargin"),
              "Reference", ("Reflect on all", "VFiveEvery"), ("Oracle", "VFiveOracle")]
# Intervention rows of the compact Table 2: label, fact tag (FInt<tag>Every, ...MarginThirty, ...RandThirty).
INTERVENTIONS = [("Doubt", "Doubt", "Doubt"), ("Self-Refine", "SelfRefine", "Self-Refine"), ("Neutral", "Neutral", "Neutral"),
                 ("+Check", "NeutralCheck", "Neutral + check"), ("+Evidence", "NeutralEvid", "Neutral + evidence"),
                 ("Reflect", "Reflect", "Reflect (neutral + evidence + check)"),
                 ("Widen + reflect", "WidenReflect", "Widen + reflect"),
                 ("Fresh", "Fresh", "Fresh mapping over the widened pool"),
                 ("Escalate", "Escalate", "Escalate (another model's first answer)")]
FULLNAME = {}  # the full table uses the same short labels
PAIRS_ALL = "DataPairs"


def macros():
    """Every \\newcommand{\\F...}{value} of numbers_v6.tex, as name (without the F) -> value text."""
    out = {}
    for m in re.finditer(r"\\newcommand\{\\F([A-Za-z]+)\}\{(.*)\}\s*$", MACROS.read_text(), re.M):
        out[m.group(1)] = m.group(2)
    return out


M = macros()


def num(key):
    if key not in M:
        sys.exit(f"numbers_v6.tex has no \\F{key}")
    return float(M[key].replace("{,}", "").replace(",", ""))


def has(key):
    return key in M


def signed(x, nd=2):
    """A signed number in math mode, so a negative value prints a true minus sign (R1)."""
    return f"${x:+.{nd}f}$"


def acc(tag):
    if has(f"{tag}Acc"):
        return num(f"{tag}Acc")
    return num("KeepAcc") + num(f"{tag}Gain")


def calls(tag):
    if tag in ("Keep", "VFiveKeep"):
        return 0.0
    return num(f"{tag}Calls")


def table(env, colspec, header, body, label, notes, colsep=4):
    """STYLE.md section 8: never scaled, \\small throughout, the caption is the writer's \\gencaption."""
    head = ["% Generated by scripts/naacl/v6_compact.py from paper/numbers_v6.tex; do not edit by hand."]
    head += [f"% {n}" for n in notes]
    return "\n".join(head + [
        rf"\begin{{{env}}}[t]",
        rf"\centering\small\setlength{{\tabcolsep}}{{{colsep}pt}}",
        rf"\begin{{tabular}}{{{colspec}}}",
        r"\toprule",
        header,
        r"\midrule",
        *body,
        r"\bottomrule",
        r"\end{tabular}",
        r"\gencaption",
        rf"\label{{{label}}}",
        rf"\end{{{env}}}",
    ]) + "\n"


def main_table():
    body = []
    for r in (ROUTERS_V5 if has("VFiveMainAcc") else ROUTERS):
        if isinstance(r, str):  # an italic group header, never a spacer row (paper/STYLE.md section 8)
            body.append(rf"\multicolumn{{4}}{{l}}{{\emph{{{r}}}}} \\")
            continue
        lab, tag = r
        bold = tag == "VFiveMain" or (tag == "Main" and not has("VFiveMainAcc"))  # Map-Reflect only
        name = rf"\textbf{{{lab}}}" if bold else lab
        if tag in ("Keep", "VFiveKeep"):
            change = "ref."
        else:
            change = signed(num(f"{tag}Gain"))  # a main-text table shows point values (STYLE.md section 8)
        body.append(f"{name} & {acc(tag):.2f} & {change} & {calls(tag):.2f} \\\\")
    return table("table", "lrrr", r"Selection & Acc. (\%) & Change & Calls \\", body, "tab:main_compact",
                 ["Compact Table 1 (R11). Full version with tokens: paper/tab6_main.tex."]), body


def interventions_table():
    body = []
    partial = []
    for lab, tag, _full in INTERVENTIONS:
        pairs = num(f"Int{tag}Pairs") if has(f"Int{tag}Pairs") else num(PAIRS_ALL)
        mark = ""
        if pairs != num(PAIRS_ALL):
            mark = r"$^{\dagger}$"
            partial.append(f"{lab}: {int(pairs):,} of {int(num(PAIRS_ALL)):,} pairs")
        cells = [signed(num(f"Int{tag}{k}")) for k in ("Every", "MarginThirty", "RandThirty")]
        body.append(f"{lab}{mark} & " + " & ".join(cells) + " \\\\")
    notes = ["Compact Table 2 (R11). Full version: paper/tab6_interventions.tex."]
    if partial:
        notes.append("The dagger marks a row measured on fewer pairs; say so in the caption: " + "; ".join(partial) + ".")
    return table("table", "lrrr", r"Strategy & All & Margin, 30\% & Random, 30\% \\", body, "tab:interventions_compact",
                 notes, colsep=2.5), body


# The confirmatory family: Margin-Reflect against five selection rules, Holm-adjusted (F-MainVs<tag>, F-MainVs<tag>Holm).
HOLM = [("No reflection", "Keep"), ("Random selection", "Rand"), ("Reflect on all", "Every"),
        ("Declined only", "Decl"), ("Full candidate list", "FullList")]

# The compact confidence-estimate table of the main text: label, fact tag, cost, held-out selection tag (or None).
SIGNALS = [(r"\textbf{Margin}", "Margin", "free", "ref"), ("Top score", "TopScore", "free", None),
           ("Ratio", "Ratio", "free", None), ("Score entropy", "ScoreEnt", "free", None),
           ("Token log-prob.", "AnsLogp", "free", "AnsLogp"), ("Stated conf.", "Stated", "paid", "Stated"),
           ("P(True)", "PTrue", "paid", "PTrue"), ("Answer entropy", "SemEnt", "paid", "SemEnt"),
           ("Logistic (paid)", "ComboPaid", "paid", "Logit")]


def holm_table():
    body = []
    for lab, tg in HOLM:
        e, lo, hi = num(f"MainVs{tg}"), num(f"MainVs{tg}Lo"), num(f"MainVs{tg}Hi")
        body.append(f"{lab} & {signed(e)} [{signed(lo)}, {signed(hi)}] & {num(f'MainVs{tg}Holm'):.4f} \\\\")
    return table("table", "lrr", r"Minus & Change [95\% CI] & Holm $p$ \\", body, "tab:holm",
                 ["The confirmatory family (F-MainVs*, F-MainVs*Holm); pooled over field-model pairs."])


def signals_table():
    body = []
    for lab, tg, cost, ho in SIGNALS:
        d = "ref." if tg == "Margin" else signed(num(f"Sig{tg}Delta"))
        h = "ref." if ho == "ref" else ("n/a" if ho is None else signed(num(f"SigHOSwap{ho}")))
        body.append(f"{lab} & {cost} & {num(f'Sig{tg}AUC'):.2f} & {num(f'Sig{tg}HOAUC'):.2f} & {d} & {h} \\\\")
    hdr = (r" & & \multicolumn{2}{c}{AUROC} & \multicolumn{2}{c}{$\Delta$ selection} \\" + "\n"
           + r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}" + "\n"
           + r"UQ method & Cost & Test & Held-out & Test & Held-out \\")
    return table("table", "llrrrr", hdr, body, "tab:signals_compact",
                 ["Compact confidence-estimate table (F-Sig*AUC, F-Sig*HOAUC, F-Sig*Delta, F-SigHOSwap*); "
                  "held-out selection is measured for the five alternatives only."], colsep=3), body


def signals_table_v5():
    """Table 4 on Map-Reflect v5's second pass (1a, DECISIONS row 51): F-VFiveSig<tag>AUC, HO<tag>AUC and
    <tag>SelVsMargin; held-out selection is measured for every estimate."""
    body = []
    for lab, tg, cost, _ in SIGNALS:
        d = "ref." if tg == "Margin" else signed(num(f"VFiveSig{tg}SelVsMargin"))
        h = "ref." if tg == "Margin" else signed(num(f"VFiveSigHO{tg}SelVsMargin"))
        body.append(f"{lab} & {cost} & {num(f'VFiveSig{tg}AUC'):.2f} & {num(f'VFiveSigHO{tg}AUC'):.2f} & {d} & {h} \\\\")
    hdr = (r" & & \multicolumn{2}{c}{AUROC} & \multicolumn{2}{c}{$\Delta$ selection} \\" + "\n"
           + r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}" + "\n"
           + r"UQ method & Cost & Test & Held-out & Test & Held-out \\")
    return table("table", "llrrrr", hdr, body, "tab:signals_compact",
                 ["Compact confidence-estimate table on Map-Reflect v5's second pass (F-VFiveSig*AUC, F-VFiveSigHO*AUC, "
                  "F-VFiveSig*SelVsMargin, F-VFiveSigHO*SelVsMargin); selection at v5's calls per model."], colsep=3), body


def heldout_selection_table_v5():
    """Held-out selection against the margin at Map-Reflect v5's calls, with intervals (F-VFiveSigHO<tag>SelVsMargin)."""
    body = []
    for lab, tg, cost, _ in SIGNALS:
        if tg == "Margin":
            continue
        k = f"VFiveSigHO{tg}SelVsMargin"
        body.append(f"{lab} & {cost} & {signed(num(k))} [{signed(num(k + 'Lo'))}, {signed(num(k + 'Hi'))}] \\\\")
    return table("table", "llr", r"UQ method & Cost & $\Delta$ vs margin [95\% CI] \\", body, "tab:signals_ho",
                 ["Held-out selection against the margin on Map-Reflect v5's second pass (F-VFiveSigHO*SelVsMargin, "
                  "pooled over the five held-out sets, at v5's calls per model)."])


def heldout_selection_table():
    """Held-out selection against the margin at the same reflection rate, with intervals (F-SigHOSwap*)."""
    body = []
    for lab, tg, cost, ho in SIGNALS:
        if ho in (None, "ref"):
            continue
        e, lo, hi = num(f"SigHOSwap{ho}"), num(f"SigHOSwap{ho}Lo"), num(f"SigHOSwap{ho}Hi")
        body.append(f"{lab} & {cost} & {signed(e)} [{signed(lo)}, {signed(hi)}] \\\\")
    return table("table", "llr", r"UQ method & Cost & $\Delta$ vs margin [95\% CI] \\", body, "tab:signals_ho",
                 ["Held-out selection against the margin (F-SigHOSwap*, pooled over the five held-out sets)."])


def no_dash(text):
    """R1: no placeholder dash and no text-mode hyphen before a digit in any cell."""
    for ln in text.splitlines():
        if ln.startswith("%") or "&" not in ln or r"\multicolumn" in ln:  # a group-header row may leave cells blank
            continue
        for x in (c.strip() for c in ln.rstrip("\\ ").split("&")):
            assert x not in ("--", "-", "---", ""), ln
            assert not re.search(r"(?<![A-Za-z])-\d", re.sub(r"\$[^$]*\$", "", x)), ln


def rows_of(path):
    """Rows of a generated full table, as first cell -> list of cells (for the cross-check only)."""
    out = {}
    for ln in path.read_text().splitlines():
        if ln.startswith("%") or "&" not in ln:
            continue
        c = [re.sub(r"\s*\[[^\]]*\]$", "", x.strip()) for x in ln.rstrip().rstrip("\\").split("&")]  # point value only
        out[c[0].replace(r"$^{\dagger}$", "")] = c
    return out


def numbers_in(cell):
    return re.findall(r"[+-]?\d+(?:\.(\d+))?", cell.replace("{,}", "")), [float(x) for x in re.findall(r"[+-]?\d+(?:\.\d+)?", cell.replace("{,}", ""))]


def agree(compact, full):
    """Every number of the compact cell matches the full cell's number to the full cell's precision."""
    if compact == full:
        return True
    _, a = numbers_in(compact)
    dec, b = numbers_in(full)
    if len(a) != len(b):
        return False
    return all(abs(x - y) <= 0.5 * 10 ** -len(d) + 0.0051 for x, y, d in zip(a, b, dec))


def cross_check(compact_body, full, pick):
    bad = 0
    for ln in compact_body:
        if "&" not in ln:
            continue
        c = [x.strip() for x in ln.rstrip().rstrip("\\").split("&")]
        key = c[0].replace(r"$^{\dagger}$", "")
        key = FULLNAME.get(key, key)
        if key not in full:
            print(f"cross-check: no row {key!r} in the full table")
            bad += 1
            continue
        want = [full[key][i] for i in pick]
        if not all(agree(a, b) for a, b in zip(c[1:], want)):
            print(f"cross-check MISMATCH {key}: compact {c[1:]} full {want}")
            bad += 1
    return bad


MR_TAG = '% group: ablation-mr (appendix "Ablation: Margin-Reflect"; listed in tab6_ablation_mr_index.tex)'


def main():
    t1, b1 = main_table()
    t2, b2 = interventions_table()
    t3 = holm_table()
    t4, _ = signals_table()
    t5 = heldout_selection_table()
    for t in (t1, t2, t3, t4, t5):
        no_dash(t)
    (ROOT / "paper/tab6_main_compact.tex").write_text(t1)
    (ROOT / "paper/tab6_interventions_compact.tex").write_text(t2)
    (ROOT / "paper/tab6_holm.tex").write_text(t3.replace("\n", "\n" + MR_TAG + "\n", 1))  # appendix group (row 35)
    if has("VFiveSigMarginAUC"):  # 1a (DECISIONS row 51): v5 under the main names, Margin-Reflect versions as _mr
        t6, _ = signals_table_v5()
        t7 = heldout_selection_table_v5()
        for t in (t6, t7):
            no_dash(t)
        mr = lambda t, n: t.replace("\n", "\n" + MR_TAG + "\n", 1).replace(f"\\label{{tab:{n}}}", f"\\label{{tab:{n}_mr}}")  # noqa: E731
        (ROOT / "paper/tab6_signals_compact_mr.tex").write_text(mr(t4, "signals_compact"))
        (ROOT / "paper/tab6_signals_ho_mr.tex").write_text(mr(t5, "signals_ho"))
        t4, t5 = t6, t7
    (ROOT / "paper/tab6_signals_compact.tex").write_text(t4)
    (ROOT / "paper/tab6_signals_ho.tex").write_text(t5)
    bad = 0
    if (ROOT / "paper/tab6_main.tex").exists():
        bad += cross_check(b1, rows_of(ROOT / "paper/tab6_main.tex"), [1, 2, 3])
    # with the v5 strategies (1b) the Margin-Reflect interventions table is tab6_interventions_mr
    full_iv = ROOT / ("paper/tab6_interventions_mr.tex" if (ROOT / "paper/tab6_interventions_mr.tex").exists()
                      else "paper/tab6_interventions.tex")
    if full_iv.exists():
        bad += cross_check(b2, rows_of(full_iv), [1, 2, 3])
    print(f"wrote paper/tab6_main_compact.tex, paper/tab6_interventions_compact.tex; cross-check against the full tables: "
          f"{'all cells agree' if not bad else f'{bad} rows differ'}")
    return bad


if __name__ == "__main__":
    sys.exit(1 if main() else 0)
